#!/usr/bin/env python3
"""Generate src/populate.sql (plain INSERT statements) from the data/*.csv files.

Usage (from the project root):
    python3 scripts/make_populate.py
    python3 scripts/make_populate.py --data data --schema src/schema.sql --out src/populate.sql

Rules (see DATA.md "CSV Conventions"):
  * empty cell  -> NULL
  * everything else is written as an escaped string literal; MySQL converts
    '123' / '2025-01-01' / '1' to INT / DATE / BOOLEAN on insert
  * scramble_sequences gets a generated Seq_Index (1, 2, ...) per scramble
Standard library only.
"""
import argparse
import csv
import re
import sys
from collections import defaultdict
from pathlib import Path

# Load order follows the foreign keys (DATA.md "Loading Notes").
TABLES = [
    "continents", "countries", "events", "formats", "allows", "staff_role",
    "regions", "teams",
    "persons", "previous_identities", "competitors", "delegate", "member_of",
    "competitions", "championship_types", "competition_delegates",
    "competition_organizers", "rounds", "cumulative_scope",
    "registrations", "selects",
    "results", "attempts",
    "scrambles", "scramble_sequences", "assigned_as", "assigned_as_slots",
]

BATCH = 500  # rows per INSERT statement


def sql_str(value: str) -> str:
    if value == "":
        return "NULL"
    v = (value.replace("\\", "\\\\").replace("'", "''")
              .replace("\r", "\\r").replace("\n", "\\n").replace("\0", ""))
    return "'" + v + "'"


def schema_columns(schema_path: Path) -> dict:
    """Crude parse of CREATE TABLE blocks -> {table: [column names]}."""
    text = schema_path.read_text(encoding="utf-8")
    text = re.sub(r"--[^\n]*", "", text)
    cols = {}
    for m in re.finditer(r"CREATE TABLE\s+(\w+)\s*\((.*?)\n\);", text, re.S):
        names = []
        for line in m.group(2).split("\n"):
            line = line.strip()
            mm = re.match(r"(\w+)\s+\w+", line)
            if mm and mm.group(1).upper() not in (
                    "CONSTRAINT", "PRIMARY", "UNIQUE", "FOREIGN", "CHECK", "KEY", "INDEX", "REFERENCES"):
                names.append(mm.group(1))
        cols[m.group(1)] = names
    return cols


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default="data")
    ap.add_argument("--schema", default="src/schema.sql")
    ap.add_argument("--out", default="src/populate.sql")
    ap.add_argument("--partial", action="store_true",
                    help="skip missing CSV files instead of failing (testing only)")
    args = ap.parse_args()

    data_dir = Path(args.data)
    expected_cols = schema_columns(Path(args.schema))
    counts = {}
    errors = []

    out = open(args.out, "w", encoding="utf-8", newline="\n")
    out.write("-- populate.sql -- generated by scripts/make_populate.py from data/*.csv\n")
    out.write("-- Run AFTER schema.sql:  mysql -u <user> -p < populate.sql\n\n")
    out.write("SET NAMES utf8mb4;\nSET FOREIGN_KEY_CHECKS = 0;  -- self-references (delegate, regions) and load order\n")
    out.write("SET UNIQUE_CHECKS = 1;\nSET autocommit = 0;\nUSE wca_db;\n\n")

    for table in TABLES:
        path = data_dir / f"{table}.csv"
        if not path.exists():
            msg = f"missing file {path}"
            if args.partial:
                print("WARNING:", msg, file=sys.stderr)
                continue
            errors.append(msg)
            continue
        if table not in expected_cols:
            errors.append(f"table {table} not found in {args.schema}")
            continue

        with open(path, newline="", encoding="utf-8-sig") as f:
            reader = csv.reader(f)
            header = next(reader)
            unknown = [h for h in header if h not in expected_cols[table]]
            if unknown:
                errors.append(f"{table}.csv has columns not in schema: {unknown}")
                continue
            columns = list(header)
            seq_counter = defaultdict(int)
            rows = []
            for lineno, row in enumerate(reader, start=2):
                if not row:
                    continue
                if len(row) != len(header):
                    errors.append(f"{path}:{lineno}: expected {len(header)} fields, got {len(row)}")
                    continue
                vals = [sql_str(c) for c in row]
                if table == "scramble_sequences":
                    key = tuple(row[:6])
                    seq_counter[key] += 1
                    vals.append(str(seq_counter[key]))
                rows.append("(" + ", ".join(vals) + ")")

        if table == "scramble_sequences":
            columns = columns + ["Seq_Index"]

        counts[table] = len(rows)
        out.write(f"-- {table}: {len(rows)} rows\n")
        collist = ", ".join(columns)
        for i in range(0, len(rows), BATCH):
            chunk = rows[i:i + BATCH]
            out.write(f"INSERT INTO {table} ({collist}) VALUES\n")
            out.write(",\n".join(chunk))
            out.write(";\n")
        out.write("COMMIT;\n\n")

    out.write("SET FOREIGN_KEY_CHECKS = 1;\n\n")
    out.write("-- Row-count check: compare with the 'expected' column (CSV row counts)\n")
    selects = [
        f"SELECT '{t}' AS tbl, COUNT(*) AS actual, {counts[t]} AS expected FROM {t}"
        for t in TABLES if t in counts
    ]
    out.write("\nUNION ALL\n".join(selects) + ";\n")
    out.close()

    if errors:
        print("ERRORS:", file=sys.stderr)
        for e in errors:
            print("  -", e, file=sys.stderr)
        return 1
    total = sum(counts.values())
    print(f"Wrote {args.out}: {len(counts)} tables, {total} rows")
    return 0


if __name__ == "__main__":
    sys.exit(main())